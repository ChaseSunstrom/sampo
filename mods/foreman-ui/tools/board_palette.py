#!/usr/bin/env python3
"""T-3701: the mod's board palette, generated from the live page's Board tokens (plugin/web/live/board-tokens.json,
T-3659), so the Board and the Claude Code mod never disagree on a colour.

  board_palette.py           write hooks/board-palette.ts from the tokens' dark scheme
  board_palette.py --check   exit 1 when hooks/board-palette.ts isn't what the tokens make (test_board runs it)

The mod ships alone (its folder is the plugin), so it can't read the repo's tokens at run time: the generated file is
committed beside it. The dark scheme only: the pane paints its own near-black ground under the body.
"""
import json
import os
import re
import sys

MOD = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOKENS = os.path.join(os.path.dirname(os.path.dirname(MOD)), "plugin", "web", "live", "board-tokens.json")
OUT = os.path.join(MOD, "hooks", "board-palette.ts")


def text(tokens_path=TOKENS):
    """board-palette.ts as the tokens make it."""
    with open(tokens_path, encoding="utf-8") as f:
        dark = json.load(f)["dark"]
    rows = []
    for k, v in dark.items():
        if not re.fullmatch(r"[a-z][a-z0-9]*", k) or not re.fullmatch(r"#[0-9a-fA-F]{6}", v):
            raise ValueError(f"board-tokens.json: {k!r}: {v!r} is not a name and a #rrggbb colour")
        rows.append(f"  {k}: 0x{v[1:].lower()},")
    return ("// Generated by tools/board_palette.py from plugin/web/live/board-tokens.json (T-3701): the Board's dark\n"
            "// scheme as numbers. Don't edit it here: change the tokens and run the tool again.\n"
            "export const BOARD = {\n" + "\n".join(rows) + "\n} as const\n")


def main():
    want = text()
    if "--check" in sys.argv[1:]:
        try:
            with open(OUT, encoding="utf-8") as f:
                same = f.read() == want
        except OSError:
            same = False
        print("board palette: " + ("matches the tokens" if same else "stale: run mods/foreman-ui/tools/board_palette.py"))
        return 0 if same else 1
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(want)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
